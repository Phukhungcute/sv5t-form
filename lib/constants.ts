export type ScheduleSettings = {
  start_date: string;

  submission_days: number;
  review1_days: number;
  addition_days: number;
  review2_days: number;
  result_days: number;

  submission_enabled: boolean;
  addition_enabled: boolean;
  result_enabled: boolean;
};


/* =====================================================
   DATE FUNCTIONS
===================================================== */

export function formatDateVN(
  date: Date
): string {
  return date.toLocaleDateString(
    "vi-VN",
    {
      day: "2-digit",
      month: "2-digit",
      year: "numeric",
      timeZone: "Asia/Ho_Chi_Minh",
    }
  );
}


export function getDateAfter(
  date: string,
  days: number
): Date {

  const result =
    new Date(date);

  result.setDate(
    result.getDate() + days
  );

  return result;
}


/* =====================================================
   PERIOD CHECK
===================================================== */

export function isWithinPeriod(
  start: string,
  end: string
): boolean {

  const now =
    new Date();

  return (
    now >= new Date(start) &&
    now < new Date(end)
  );
}


/* =====================================================
   SCHEDULE
===================================================== */

export function buildSchedule(
  settings: ScheduleSettings
) {

  const start =
    new Date(settings.start_date);


  /*
    Mỗi period dùng:
    
    start = ngày bắt đầu
    end   = ngày bắt đầu + số ngày
    
    end là mốc EXCLUSIVE khi kiểm tra thời gian.
  */


  const submissionStart =
    getDateAfter(
      settings.start_date,
      0
    );

  const submissionEnd =
    getDateAfter(
      settings.start_date,
      settings.submission_days
    );


  const review1Start =
    getDateAfter(
      settings.start_date,
      settings.submission_days
    );

  const review1End =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days
    );


  const additionStart =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days
    );

  const additionEnd =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days
    );


  const review2Start =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days
    );

  const review2End =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days +
        settings.review2_days
    );


  const resultStart =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days +
        settings.review2_days
    );

  const resultEnd =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days +
        settings.review2_days +
        settings.result_days
    );


  return {

    startDate:
      formatDateVN(start),

    submission: {
      start:
        formatDateVN(
          submissionStart
        ),

      end:
        formatDateVN(
          getDateAfter(
            settings.start_date,
            settings.submission_days - 1
          )
        ),

      enabled:
        settings.submission_enabled,
    },


    review1: {
      start:
        formatDateVN(
          review1Start
        ),

      end:
        formatDateVN(
          getDateAfter(
            settings.start_date,
            settings.submission_days +
              settings.review1_days -
              1
          )
        ),
    },


    addition: {
      start:
        formatDateVN(
          additionStart
        ),

      end:
        formatDateVN(
          getDateAfter(
            settings.start_date,
            settings.submission_days +
              settings.review1_days +
              settings.addition_days -
              1
          )
        ),

      enabled:
        settings.addition_enabled,
    },


    review2: {
      start:
        formatDateVN(
          review2Start
        ),

      end:
        formatDateVN(
          getDateAfter(
            settings.start_date,
            settings.submission_days +
              settings.review1_days +
              settings.addition_days +
              settings.review2_days -
              1
          )
        ),
    },


    result: {
      start:
        formatDateVN(
          resultStart
        ),

      end:
        formatDateVN(
          getDateAfter(
            settings.start_date,
            settings.submission_days +
              settings.review1_days +
              settings.addition_days +
              settings.review2_days +
              settings.result_days -
              1
          )
        ),

      enabled:
        settings.result_enabled,
    },

  };
}

export function isSubmissionPeriod(
  settings: ScheduleSettings
): boolean {

  const start =
    new Date(settings.start_date);

  const end =
    getDateAfter(
      settings.start_date,
      settings.submission_days
    );

  return isWithinPeriod(
    start.toISOString(),
    end.toISOString()
  );
}

export function isAdditionPeriod(
  settings: ScheduleSettings
): boolean {

  const start =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days
    );

  const end =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days
    );

  return isWithinPeriod(
    start.toISOString(),
    end.toISOString()
  );
}

export function isResultPeriod(
  settings: ScheduleSettings
): boolean {

  const start =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days +
        settings.review2_days
    );

  const end =
    getDateAfter(
      settings.start_date,
      settings.submission_days +
        settings.review1_days +
        settings.addition_days +
        settings.review2_days +
        settings.result_days
    );

  return isWithinPeriod(
    start.toISOString(),
    end.toISOString()
  );
}

